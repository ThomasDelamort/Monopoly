    private string _text = "";
    private float _pixel = 4f;

    public PixelText() { }

    public PixelText(string text, float pixelSize = 4f, Color? color = null)
    {
        _text = text;
        _pixel = pixelSize;
        if (color.HasValue) Color = color.Value;
        MouseFilter = MouseFilterEnum.Ignore;
        UpdateMinimumSize();
    }

    public Color Color { get; set; } = Palette.Accent;
    public bool Glow { get; set; } = true;

    public string Text
    {
        get => _text;
        set
        {
            _text = value;
            UpdateMinimumSize();
            QueueRedraw();
        }
    }

    public float PixelSize
    {
        get => _pixel;
        set
        {
            _pixel = value;
            UpdateMinimumSize();
            QueueRedraw();
        }
    }

    public override Vector2 _GetMinimumSize() => new(MeasureWidth() * _pixel, 7 * _pixel);

    private int MeasureWidth()
    {
        int width = 0;
        foreach (char ch in _text.ToUpperInvariant())
            width += (Glyphs.TryGetValue(ch, out var g) ? g[0].Length : 3) + 1;
        return width > 0 ? width - 1 : 0;
    }

    public override void _Draw()
    {
        float startX = (Size.X - MeasureWidth() * _pixel) / 2f;
        float startY = (Size.Y - 7 * _pixel) / 2f;
        for (int pass = Glow ? 0 : 1; pass < 2; pass++)
        {
            float x = startX;
            foreach (char raw in _text.ToUpperInvariant())
            {
                if (!Glyphs.TryGetValue(raw, out var glyph)) glyph = Glyphs[' '];
                for (int row = 0; row < 7; row++)
                for (int col = 0; col < glyph[row].Length; col++)
                {
                    if (glyph[row][col] != '1') continue;
                    var cell = new Rect2(x + col * _pixel, startY + row * _pixel, _pixel, _pixel);
                    if (pass == 0) DrawRect(cell.Grow(_pixel * 0.6f), Color with { A = 0.16f });
                    else DrawRect(cell.Grow(-_pixel * 0.06f), Color);
                }
                x += (glyph[0].Length + 1) * _pixel;
            }
        }
    }
